// Copies contract ABIs and deployments from contracts/ into src/.
// Run after `forge build` (and after a deploy): pnpm --filter @jitu-fi/shared sync:contracts
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, "..", "..", "..", "contracts");
const src = join(here, "..", "src");

const CONTRACTS = [
  ["MockUSD", "mocks/MockUSD.sol"],
  ["MockYieldStrategy", "mocks/MockYieldStrategy.sol"],
  ["SeasonVault", "SeasonVault.sol"],
  ["GameManager", "GameManager.sol"],
];
const CHAIN_IDS = [10143];

const header = "// Generated by scripts/sync-contracts.mjs from contracts/. Do not edit.\n";

mkdirSync(join(src, "abis"), { recursive: true });
const abiExports = [];
for (const [name, file] of CONTRACTS) {
  const artifact = join(contracts, "out", file.split("/").pop(), `${name}.json`);
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  const constName = `${name[0].toLowerCase()}${name.slice(1)}Abi`;
  writeFileSync(
    join(src, "abis", `${name}.ts`),
    `${header}export const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  abiExports.push(`export { ${constName} } from "./${name}.js";`);
}
writeFileSync(join(src, "abis", "index.ts"), `${header}${abiExports.join("\n")}\n`);

mkdirSync(join(src, "deployments"), { recursive: true });
for (const chainId of CHAIN_IDS) {
  const file = join(contracts, "deployments", `${chainId}.json`);
  if (!existsSync(file)) continue;
  const d = JSON.parse(readFileSync(file, "utf8"));
  writeFileSync(join(src, "deployments", `${chainId}.ts`), `${header}export default ${JSON.stringify(d, null, 2)} as const;\n`);
}
console.log(`Synced ${CONTRACTS.length} ABIs and deployments for ${CHAIN_IDS.join(", ")}`);
